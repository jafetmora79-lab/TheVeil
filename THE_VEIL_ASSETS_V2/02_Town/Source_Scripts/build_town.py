#!/usr/bin/env python3
"""THE VEIL - Pack 02 builder: town kit models + Greyhaven layout.

    python3 02_Town/Source_Scripts/build_town.py

Steps
  1. Pack 02 supplementary textures + materials   (build_textures.py)
  2. Every kit model -> GLB (+ Godot .import mapping to Pack 01/02 .tres) + OBJ/MTL
  3. Greyhaven layout -> TOWN_*.glb + Godot_Scenes/Greyhaven_Town.tscn + layout JSON
  4. Model manifest -> Documentation/MODEL_MANIFEST.json/.md
Deterministic: identical inputs produce identical files.
"""
import json
import os
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, HERE)
sys.path.insert(0, os.path.join(HERE, "..", "..", "Source_Scripts"))

import build_textures  # noqa: E402
from veil_mesh.materials import TOWN, V2, MATS  # noqa: E402
from veil_mesh.gltf import GLBWriter, write_glb_import, write_obj, COL_KEY  # noqa: E402

import models_roads  # noqa: E402
import models_props  # noqa: E402
import models_nature  # noqa: E402

ALL_MODELS = models_roads.ROAD_MODELS + models_props.PROP_MODELS + models_nature.NATURE_MODELS


def strip_meta(spec):
    return {k: v for k, v in spec.items() if k != "meta"}


def export_model(cat, spec, obj=True):
    d = os.path.join(TOWN, cat)
    os.makedirs(d, exist_ok=True)
    glb = os.path.join(d, spec["name"] + ".glb")
    used = GLBWriter(glb).write(strip_meta(spec))
    write_glb_import(glb, used)
    if obj:
        od = os.path.join(d, "OBJ")
        os.makedirs(od, exist_ok=True)
        write_obj(os.path.join(od, spec["name"] + ".obj"), spec["name"], strip_meta(spec))
    return glb, used


def summarize(cat, spec, glb, used):
    vis_tris, col_tris, cols = 0, 0, []

    def walk(n):
        nonlocal vis_tris, col_tris
        mb = n.get("mb")
        if mb is not None:
            if "-col" in n["name"] or "colonly" in n["name"]:
                col_tris += mb.tri_count()
                cols.append(n["name"].split("-")[-1])
            else:
                vis_tris += mb.tri_count()
        for c in n.get("children", []):
            walk(c)
    walk(spec)
    meta = spec.get("meta", {})
    import numpy as np
    vis = spec["children"][0]["mb"]
    mn, mx = vis.bounds()
    return {
        "name": spec["name"], "category": cat, "glb": os.path.relpath(glb, V2).replace(os.sep, "/"),
        "obj": f"02_Town/{cat}/OBJ/{spec['name']}.obj",
        "triangles": vis_tris, "collision_triangles": col_tris, "collision": sorted(set(cols)) or ["none"],
        "materials": used, "bounds_min": [round(float(v), 3) for v in mn], "bounds_max": [round(float(v), 3) for v in mx],
        "nodes": [c["name"] for c in spec["children"]],
        **{k: v for k, v in meta.items()},
    }


def main():
    build_textures.main()
    manifest = []
    for cat, fn in ALL_MODELS:
        spec = fn()
        glb, used = export_model(cat, spec)
        manifest.append(summarize(cat, spec, glb, used))
    # street-name sign variants used by the layout
    import town_layout
    for (a, b) in town_layout.STREET_SIGN_PAIRS:
        spec = models_props.street_name_sign(a, b)
        if any(m["name"] == spec["name"] for m in manifest):
            continue
        glb, used = export_model("Street_Props", spec)
        manifest.append(summarize("Street_Props", spec, glb, used))
    spec_fn = {}
    for cat, fn in ALL_MODELS:
        spec_fn[fn()["name"]] = fn
    layout_info = town_layout.build(manifest, spec_fn)
    doc = os.path.join(TOWN, "Documentation")
    os.makedirs(doc, exist_ok=True)
    with open(os.path.join(doc, "MODEL_MANIFEST.json"), "w", newline="\n") as f:
        json.dump({"pack": "THE VEIL - Pack 02 Greyhaven Town", "models": manifest, "layout": layout_info}, f, indent=1)
    write_manifest_md(manifest, os.path.join(doc, "MODEL_MANIFEST.md"))
    print(f"{len(manifest)} kit models exported; layout: {layout_info['instances']} instances")


def write_manifest_md(manifest, path):
    lines = ["# THE VEIL - Pack 02 Model Manifest", "",
             "Generated by `02_Town/Source_Scripts/build_town.py`. Triangle counts are visual meshes; collision listed separately.", ""]
    cats = []
    for m in manifest:
        if m["category"] not in cats:
            cats.append(m["category"])
    for c in cats:
        ms = [m for m in manifest if m["category"] == c]
        lines += [f"## {c} ({len(ms)})", "", "| Model | Tris | Collision | Materials | Notes |", "|---|---|---|---|---|"]
        for m in ms:
            note = m.get("desc") or m.get("note") or ""
            if m.get("ports"):
                note = (note + " ").strip() + f" ports: {len(m['ports'])}"
            if m.get("interactive"):
                note = "**interactive** " + note
            lines.append(f"| `{m['name']}` | {m['triangles']} | {', '.join(m['collision'])} ({m['collision_triangles']}) | "
                         f"{len(m['materials'])} | {note} |")
        lines.append("")
    with open(path, "w", newline="\n") as f:
        f.write("\n".join(lines) + "\n")


if __name__ == "__main__":
    main()
