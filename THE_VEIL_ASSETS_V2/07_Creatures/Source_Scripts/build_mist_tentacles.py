def scaled_path(v):
    P = np.array(v["path"], float)
    Cd = G.resample(P, 60)
    _, Lp = G.arclen(Cd)
    return [tuple(p * v["L"] / Lp) for p in P]


def at_s(Cd, s):
    """centre, tangent, back axis (a), side axis (b) at normalised arc length s (front = underside = -a)."""
    S_, _ = G.arclen(Cd)
    T, A, Bv = G.frames(Cd, (0, -1, 0))
    i = int(np.clip(np.searchsorted(S_, s), 1, len(S_) - 1))
    t = (s - S_[i - 1]) / max(S_[i] - S_[i - 1], 1e-9)
    lerp = lambda X_: X_[i - 1] + (X_[i] - X_[i - 1]) * t  # noqa: E731
    return lerp(Cd), C.nrm(lerp(T)), C.nrm(lerp(A)), C.nrm(lerp(Bv))


def build_variant(key, v, uv):
    name = f"CRT_MistTentacle_{key}"
    rig = C.Rig(name)
    rig.add("Root", None, (0, 0, 0))
    path = scaled_path(v)
    bones, jp, Cd = B.tentacle_chain(rig, "T", "Root", path, NB, samples=NB * 4 + 1)
    tent, atl = C.SkinMesh(), C.SkinMesh()
    meshes = {"M_Crt_Tentacle": tent, "M_Crt_MistTentacle": atl}
    L = B.tentacle_mesh(tent, Cd, bones, jp, v["r0"], v["rtip"], (0, 0, 1, 1), n=v["n"], ridge=0.09, front=(0, -1, 0), parent="Root", root_blend=0.12,
                        ridges=v["ridges"], flat=v["flat"], seed=len(key), tile_m=TILE_M, flare=v["flare"])
    # base cap hidden in the mist: close the flared bottom so the base never looks hollow
    stops = G.stops_from_joints(Cd, jp[:-1], bones)
    wf = G.chain_w(stops, blend=0.05)
    S_, _ = G.arclen(Cd)

    def radius(s):
        return (v["rtip"] + (v["r0"] - v["rtip"]) * (1 - s) ** 0.9) * (1.0 + v["flare"] * math.exp(-(s / 0.05) ** 2))
    base_r = radius(0.0)
    G.orb(atl, (0, base_r * 0.12, 0), base_r * 0.98, {"Root": 1.0}, uv["flesh"], n=v["n"], m=3, axis=(0, 1, 0),
          squash=(1.0, 1.0, 0.1))
    if key == "Thin":
        c, t, a, b = at_s(Cd, 1.0)
        tipb = bones[-1]
        G.orb(atl, c + t * v["rtip"] * 2, 0.045, {tipb: 1.0}, uv["bulb"], n=6, m=4, axis=t)
        for side in (-1, 1):
            p0 = c + t * 0.03
            fil = [p0, p0 + t * 0.12 + b * side * 0.06 - a * 0.02, p0 + t * 0.24 + b * side * 0.14 + a * 0.03]
            G.sweep(atl, G.resample(fil, 5), [0.012, 0.01, 0.008, 0.006, 0.004], lambda p, s, bb=tipb: {bb: 1.0},
                    uv["claw"], n=4, tip=0.03)
        for q, s in enumerate(np.linspace(0.18, 0.85, 9)):
            c, t, a, b = at_s(Cd, s)
            side = 1 if q % 2 else -1
            p = c - a * radius(s) * 0.85 + b * side * radius(s) * 0.45
            G.orb(atl, p, radius(s) * 0.32, wf(p, s), uv["node"], n=5, m=3, axis=C.nrm(-a + b * side * 0.5))
    elif key == "Medium":
        for q, s in enumerate(np.linspace(0.42, 0.93, 9)):
            c, t, a, b = at_s(Cd, s)
            r = radius(s)
            for side in (-1, 1):
                base = c - a * r * 0.7 + b * side * r * 0.55
                hook = [base, base - a * r * 0.9 + b * side * r * 0.2 - t * r * 0.2,
                        base - a * r * 1.25 - t * r * 0.9]
                G.sweep(atl, G.resample(hook, 4), [r * 0.22, r * 0.16, r * 0.1, r * 0.05], lambda p, ss, s=s: wf(p, s),
                        uv["barb"], n=4, tip=r * 0.25, front=tuple(t))
        c, t, a, b = at_s(Cd, 1.0)
        hook = [c, c + t * 0.12 - a * 0.05, c + t * 0.18 - a * 0.2]
        G.sweep(atl, G.resample(hook, 4), [0.05, 0.04, 0.025, 0.012], lambda p, s: {bones[-1]: 1.0}, uv["claw"], n=5,
                tip=0.06, front=tuple(t))
    else:
        for q, s in enumerate(np.linspace(0.08, 0.72, 11)):
            c, t, a, b = at_s(Cd, s)
            r = radius(s)
            side = (q % 3 - 1) * 0.35
            nv = C.nrm(a + b * side)
            p = c + nv * r * 0.9
            G.plate(atl, p, (r * 1.3, r * 0.22, r * 1.6), wf(p, s), uv["plate"], normal=nv, along=t + nv * 0.3,
                    taper=(0.6, 0.7))
        c, t, a, b = at_s(Cd, 0.55)
        r = radius(0.55)
        for k in range(5):
            ang = 2 * math.pi * k / 5 + 0.3
            nv = a * math.cos(ang) + b * math.sin(ang)
            p = c + nv * r * 1.02
            G.plate(atl, p, (r * 0.8, r * 0.25, r * 0.9), wf(p, 0.55), uv["plate"], normal=nv, along=t, taper=(0.5, 0.6))
        c, t, a, b = at_s(Cd, 1.0)
        spike = [c - t * 0.1, c + t * 0.25 + a * 0.05, c + t * 0.55 - a * 0.12, c + t * 0.7 - a * 0.35]
        G.sweep(atl, G.resample(spike, 6), [0.09, 0.08, 0.06, 0.045, 0.03, 0.015], lambda p, s: {bones[-1]: 1.0},
                uv["spike"], n=5, tip=0.1, front=tuple(-a))
    return rig, bones, meshes, L


# ------------------------------------------------------------------ shared clips (one set, scaled by length)
def clips_for(rig, bones, L):
    n = len(bones)
    radii = [0.3] * (n + 1)

    def guard(local, trans, floor=0.05):
        return B.floor_clamp(rig, local, trans, bones, floor, step=3.0, rad=radii)

    def search_pose(t, T=6.0, amt=1.0):
        local, trans = {}, {}
        B.wave(rig, local, bones, t, amp=9.0 * amt, amp2=8.0 * amt, freq=0.34, lag=0.6, phase=0.4, period=T)
        f = B.cyc(1.4, T)
        for k, b in enumerate(bones[-3:]):
            local[b] = local[b] @ C.R((1, 0, 0), 6.0 * amt * math.sin(2 * math.pi * f * t + k * 1.3))
        return local, trans

    def search(t):
        local, trans = search_pose(t)
        return guard(local, trans), trans

    def coiled(local, amt, t=0.0, T=4.0):
        f = B.cyc(0.5, T)
        breath = 1.0 + 0.08 * math.sin(2 * math.pi * f * t)
        B.curl(rig, local, bones[:2], [-8 * amt, -6 * amt])
        B.curl(rig, local, bones[2:], [-31 * amt * breath * (0.75 + 0.5 * k / (n - 2)) for k in range(n - 2)])
        B.curl(rig, local, bones[2:], [9 * amt] * (n - 2), axis="sweep")
        return local

    def coil(t):
        T = 4.0
        local, trans = search_pose(t, T, 0.35)
        coiled(local, 1.0, t, T)
        return guard(local, trans), trans

    def emerge(t):
        e = C.ease(t, 0.0, 2.0)
        u = C.ease(t, 0.35, 2.6)
        local, trans = search_pose(0.0, amt=u)
        coiled(local, 1.0 - u)
        trans["Root"] = (0, -L * 1.05 * (1 - e), 0)
        return local, trans

    def retract(t):
        u = C.ease(t, 0.0, 1.2)
        e = C.ease(t, 0.35, 2.2)
        local, trans = search_pose(t, amt=1 - u)
        coiled(local, u)
        trans["Root"] = (0, -L * 1.05 * e, 0)
        return local, trans

    def aim_all(local, trans, dirs, amt):
        # the two root bones turn less, so the base stays seated in the mist while the rest of the chain moves
        for k, (b, d) in enumerate(zip(bones, dirs)):
            local = B.aim_world(rig, local, trans, b, d, amt * min(1.0, 0.3 + 0.3 * k))
        return local

    def reach(t):
        r = C.ease(t, 0.1, 1.3)
        local, trans = search_pose(t, amt=0.4)
        dirs = [(0, 1.0 - 0.07 * k, 0.25 + 0.12 * k) for k in range(n)]
        local = aim_all(local, trans, dirs, 0.75 * r)
        f = 1.6
        for k, b in enumerate(bones[-3:]):
            local[b] = local[b] @ C.R((0, 1, 0), 7.0 * r * math.sin(2 * math.pi * f * t + k))
        return guard(local, trans), trans

    def strike(t):
        w = C.pulse(t, 0.0, 0.55, 0.6, 0.75)
        h = C.pulse(t, 0.62, 0.82, 1.05, 1.8)
        local, trans = search_pose(t, amt=0.3)
        back = [(0, 1.0, -0.15 - 0.1 * k) for k in range(n)]
        local = aim_all(local, trans, back, 0.6 * w)
        fwd = [(0, 1.0 - 0.17 * k, 0.6 + 0.08 * k) for k in range(n)]
        local = aim_all(local, trans, fwd, 0.85 * h)
        return guard(local, trans, floor=0.02), trans

    return [("Emerge", emerge, 2.6, False), ("Search", search, 6.0, True), ("Coil", coil, 4.0, True),
            ("Reach", reach, 2.2, False), ("Strike", strike, 1.8, False), ("Retract", retract, 2.2, False)]


def build():
    tent_png, atlas_png, uv = textures()
    mats = {"M_Crt_Tentacle": dict(albedo=tent_png[0], emit=tent_png[1], emit_factor=(0.5, 0.55, 0.58), emit_energy=0.5,
                                   repeat=True, rough=0.7),
            "M_Crt_MistTentacle": dict(albedo=atlas_png[0], emit=atlas_png[1], emit_factor=(0.6, 0.65, 0.68), emit_energy=0.6,
                                       repeat=False, rough=0.75)}
    out = []
    script = os.path.join(C.CR, "Godot_Scenes", "veil_mist_tentacle.gd")
    for key, v in VARIANTS.items():
        rig, bones, meshes, L = build_variant(key, v, uv)
        clips, frames = [], {}
        for nm, fn, dur, loop in clips_for(rig, bones, L):
            c, fr = C.bake(rig, nm, fn, dur, FPS, loop)
            clips.append(c)
            frames[nm] = fr
        name = rig.name
        sockets = [("Socket_Tip", bones[-1], rig.tips[bones[-1]])]
        extras = {"veil_creature": "MistTentacle", "variant": key, "length_m": round(L, 3), "faces": "+Z",
                  "shared_skeleton": ["Root"] + bones}
        glb, tris = B.export(name, "Mist_Tentacles", rig, meshes, mats, sockets, clips, extras)
        P = np.array([p for sm in meshes.values() for p in sm.P])
        mid = (P.max(0) + P.min(0)) / 2
        ext = P.max(0) - P.min(0)
        scene = os.path.join(C.CR, "Godot_Scenes", f"{name}.tscn")
        S.creature_scene(
            scene, f"MistTentacle_{key}", glb,
            shapes=[("Bounds", "CapsuleShape3D", {"radius": round(max(ext[0], ext[2]) / 2 + v["r0"], 3),
                                                   "height": round(ext[1] + v["r0"] * 2, 3)}, (mid[0], ext[1] / 2, mid[2]))],
            markers=[("/MistRoot", (0, 0, 0))],
            meta={"veil_creature": "MistTentacle", "variant": key, "animation_player": "Model/AnimationPlayer",
                  "animations": [c.name for c in clips], "length_m": round(L, 3)},
            script=script, root_type="Node3D", shape_parent="BoundsArea",
            props={"fade_height": f"{round(0.12 * L, 3):g}"})
        out.append(dict(name=name, glb=glb, tris=tris, rig=rig, clips=clips, frames=frames, meshes=meshes, mats=mats,
                        sockets=sockets, probe=bones[-1], edge_floor=0.03,
                        scene=os.path.relpath(scene, C.V2).replace(os.sep, "/"),
                        limits={"max_stretch": 1.8, "max_stretch_death": 1.8, "p999_stretch": 1.4, "p999_stretch_death": 1.4,
                                "min_y": -0.08, "min_y_exempt": ["Emerge", "Retract"], "override_materials": True}))
    return out


