"""THE VEIL - Pack 07 / Creature 02: MIST TENTACLES (environmental predator; no visible body).

Three reusable variants share one skeleton (Root + T_01..T_10) and one clip set, generated by the same pose
functions scaled by length:
  * Thin    (3.4 m) - searching tentacle: wavy, upright, dense ridges, a pale sensory bulb and two filaments at
                      the tip, tiny sensory nodes along the underside.
  * Medium  (5.2 m) - grasping tentacle: flattened underside lined with paired hooked barbs, tip curled into a hook.
  * Large   (7.8 m) - aggressive tentacle: hunched forward, overlapping bone plates down the back, a knuckled
                      kink ringed with plates at 55 %, a hooked bone spike at the tip.
Each rises from a flared base that sinks into the mist. Root (at the origin) is the placement / mist-surface bone:
Emerge and Retract move it below the mist (the scene dithers everything under the mist surface away).
Materials: M_Crt_Tentacle (shared tiling skin) + M_Crt_MistTentacle (128 px detail atlas).
"""
