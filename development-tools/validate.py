class Checks:
    def __init__(self):
        self.errors = 0

    def error(self, message):
        self.errors += 1
        print(f"FAIL {message}")


def inventory(root):
    return {
        p.relative_to(root).as_posix()
        for p in root.rglob("*")
        if p.is_file() and not SKIP.intersection(p.relative_to(root).parts)
    }


def check_gltf(path, root, files, checks):
    try:
        if path.suffix == ".gltf":
            model = json.loads(path.read_text(encoding="utf-8"))
        else:
            with path.open("rb") as stream:
                magic, version, size, length, kind = struct.unpack("<4sIII4s", stream.read(20))
                if (magic, version, kind) != (b"glTF", 2, b"JSON"):
                    raise ValueError("expected GLB 2 JSON chunk")
                if size != path.stat().st_size or not 0 < length <= size - 20 or length % 4:
                    raise ValueError("invalid GLB length")
                model = json.loads(stream.read(length))
        for key in ("buffers", "images"):
            for item in model.get(key, []):
                if "uri" not in item:
                    continue
                uri = urlsplit(item["uri"])
                if uri.scheme == "data":
                    continue
                if uri.scheme or uri.netloc:
                    checks.error(f"{path.relative_to(root)}: external {key} URI {item['uri']}")
                    continue
                target = posixpath.normpath(
                    posixpath.join(path.parent.relative_to(root).as_posix(), unquote(uri.path))
                )
                if target not in files:
                    checks.error(f"{path.relative_to(root)}: missing {key} URI {item['uri']}")
    except (OSError, ValueError, struct.error, AttributeError, TypeError) as exc:
        checks.error(f"{path.relative_to(root)}: {exc}")


def check_project(root, required, checks):
    files = inventory(root)
    for name in sorted(set(REQUIRED + required)):
        if name.removeprefix("res://") not in files or not name.endswith(".tscn"):
            checks.error(f"required scene {name}")
    if "project.godot" not in files:
        checks.error("missing root project.godot")
    else:
        config = (root / "project.godot").read_text(encoding="utf-8-sig")
        if not re.search(r"(?m)^\s*run/main_scene\s*=\s*\"(?:res|uid)://[^\" ]+\"", config):
            checks.error("project.godot: missing main scene")
    count = 0
    for name in sorted(files):
        path = root / name
        if path.suffix in {".glb", ".gltf"}:
            check_gltf(path, root, files, checks)
        if path.suffix not in TEXT_TYPES:
            continue
        source = path.read_text(encoding="utf-8-sig")
        definitions = {"Ext": set(), "Sub": set()}
        references = []
        for number, line in enumerate(source.splitlines(), 1):
            if line.lstrip().startswith(("#", ";", "//")):
                continue
            for match in re.finditer(r'"res://([^"]+)"', line):
                target = match[1]
                # Import cache destinations are generated by Godot.
                if path.suffix == ".import" and target.startswith(".godot/imported/"):
                    continue
                # Directory literals are valid in scripts.
                if target not in files and not (target.endswith("/") and (root / target).is_dir()):
                    checks.error(f"{name}:{number}: missing or case-mismatched res://{target}")
                count += 1
            if path.suffix in {".tscn", ".tres"}:
                definition = re.match(r'^\[(ext|sub)_resource\b.*\bid="([^"]+)"', line)
                if definition:
                    group = definitions[definition[1].title()]
                    if definition[2] in group:
                        checks.error(f"{name}:{number}: duplicate resource ID {definition[2]}")
                    group.add(definition[2])
                references.extend((number, *match.groups()) for match in
                                  re.finditer(r'\b(Ext|Sub)Resource\("([^"]+)"\)', line))
        for number, kind, identifier in references:
            if identifier not in definitions[kind]:
                checks.error(f"{name}:{number}: undefined {kind}Resource({identifier})")
    print(f"Checked {count} literal Godot paths and GLB/glTF external dependencies.")
    print("Godot import and parsing are separate engine checks.")


class PageAssets(HTMLParser):
    def __init__(self):
        super().__init__()
        self.urls = []

    def handle_starttag(self, tag, attrs):
        for key, value in attrs:
            if value and (key == "src" or (tag == "link" and key == "href")):
                self.urls.append(value)


def check_web(root, site, entry, checks):
    config_path = root / "project.godot"
    if not config_path.is_file():
        checks.error("missing project.godot")
    else:
        config = config_path.read_text(encoding="utf-8-sig")
        sections = re.split(r"(?m)^\s*\[([^\]]+)\]\s*$", config)
        rendering = dict(zip(sections[1::2], sections[2::2])).get("rendering", "")
        methods = dict(re.findall(
            r'(?m)^\s*renderer/(rendering_method(?:\.web)?)\s*=\s*"([^"]+)"', rendering
        ))
        if methods.get("rendering_method.web", methods.get("rendering_method")) != "gl_compatibility":
            checks.error("set explicit gl_compatibility renderer for Web")
    presets_path = root / "export_presets.cfg"
    if not presets_path.is_file():
        checks.error("missing export_presets.cfg")
    else:
        presets = presets_path.read_text(encoding="utf-8-sig")
        web_presets = [part for part in re.split(r"(?m)(?=^\[preset\.\d+\]\s*$)", presets)
                       if re.search(r'(?m)^platform\s*=\s*"Web"', part)]
        if not web_presets:
            checks.error("no Godot Web preset")
        for preset in web_presets:
            if re.search(r"(?m)^variant/(thread_support|extensions_support)\s*=\s*true", preset):
                checks.error("Web preset requires cross-origin isolation; use a single-threaded standard export for this Pages check")
    files = inventory(site)
    for name, expected in GALLERY.items():
        if name not in files:
            checks.error(f"missing gallery file: {name}")
            continue
        payload = (site / name).read_bytes()
        digest = hashlib.sha1(f"blob {len(payload)}\0".encode() + payload).hexdigest()
        if digest != expected:
            checks.error(f"gallery differs from pinned baseline: {name}")
    build = Path(entry)
    if build.is_absolute() or ".." in build.parts or len(build.parts) < 2 or build.suffix != ".html":
        checks.error("use a nested Pages entry such as play/index.html")
        return
    for suffix in (".html", ".js", ".wasm", ".pck"):
        name = build.with_suffix(suffix).as_posix()
        if name not in files or not (site / name).stat().st_size:
            checks.error(f"missing or empty Web file {name}")
        elif suffix in {".wasm", ".pck"}:
            with (site / name).open("rb") as stream:
                if stream.read(4) != {".wasm": b"\0asm", ".pck": b"GDPC"}[suffix]:
                    checks.error(f"{name}: invalid file signature")
    if build.as_posix() in files:
        page = PageAssets()
        html = (site / build).read_text(encoding="utf-8-sig")
        page.feed(html)
        config = re.search(r'\bGODOT_CONFIG\s*=\s*(\{[^\n]+\})\s*;', html)
        if not config:
            checks.error("expected stock Godot HTML shell with GODOT_CONFIG")
        else:
            try:
                options = json.loads(config[1])
                if options.get("executable") != build.stem:
                    checks.error(f"{entry}: executable should be {build.stem}")
                for name, size in options.get("fileSizes", {}).items():
                    if name != Path(name).name or "\\" in name:
                        checks.error(f"{entry}: invalid fileSizes name {name}")
                    else:
                        target = (build.parent / name).as_posix()
                        if target not in files or (site / target).stat().st_size != size:
                            checks.error(f"{target}: missing or size differs from GODOT_CONFIG")
            except (ValueError, AttributeError, TypeError) as exc:
                checks.error(f"{entry}: invalid GODOT_CONFIG: {exc}")
        if build.with_suffix(".js").name not in page.urls:
            checks.error(f"{entry}: expected relative loader script {build.with_suffix('.js').name}")
        for value in page.urls:
            url = urlsplit(value)
            if url.scheme or url.netloc or not url.path:
                continue
            raw_path = unquote(url.path)
            target = posixpath.normpath(posixpath.join(build.parent.as_posix(), raw_path))
            if target not in files:
                checks.error(f"{entry}: broken or root-relative asset URL {value}")
    print("Static Pages staging check. Browser launch, HTTPS, response headers and live Pages settings require a separate check.")


def check_route(path, planned_distance, checks):
    """Analyze one chronological run of the actual sedan, with ordered route checkpoints."""
    data = json.loads(path.read_text(encoding="utf-8-sig"))
    checkpoints = data["checkpoints"]
    samples = data["samples"]

    def position(row):
        xyz = row["xyz"]
        if len(xyz) != 3 or not all(type(x) in (int, float) and math.isfinite(x) for x in xyz):
            raise ValueError("xyz must be three finite numbers")
        return xyz

    if len(checkpoints) < 2 or len(samples) < 2:
        raise ValueError("need at least two checkpoints and two samples")
    positions = [position(row) for row in samples]
    times = [row["t"] for row in samples]
    if any(type(t) not in (int, float) or not math.isfinite(t) for t in times):
        raise ValueError("sample times must be finite numbers")
    if any(not 0 < b - a <= 0.25 for a, b in zip(times, times[1:])):
        raise ValueError("sample times must increase with gaps of at most 0.25 s")
    targets = [(position(row), row["radius_m"]) for row in checkpoints]
    if any(type(radius) not in (int, float) or not math.isfinite(radius) or radius <= 0
           for _, radius in targets):
        raise ValueError("checkpoint radii must be finite and positive")
    if math.dist(positions[0], targets[0][0]) > targets[0][1]:
        raise ValueError("first sample must be inside the departure checkpoint")
    next_checkpoint = 1
    end = None
    for index, xyz in enumerate(positions[1:], 1):
        target, radius = targets[next_checkpoint]
        if math.dist(xyz, target) <= radius:
            next_checkpoint += 1
            if next_checkpoint == len(targets):
                end = index
                break
    if end is None:
        checks.error(f"reachability unverified in this run ({next_checkpoint}/{len(targets)} ordered checkpoints)")
        return
    travel = positions[:end + 1]
    distance = sum(math.dist(a, b) for a, b in zip(travel, travel[1:]))
    if distance <= 0:
        raise ValueError("completed run has no movement")
    elapsed = times[end] - times[0]
    speed = distance / elapsed
    print(f"Reached destination. Sampled distance {distance:.1f} m. Average {speed:.2f} m/s ({speed * 3.6:.1f} km/h).")
    print(f"Measured duration {elapsed:.2f} s.")
    if planned_distance is not None:
        if not math.isfinite(planned_distance) or planned_distance <= 0:
            raise ValueError("planned distance must be finite and positive")
        print(f"Estimated duration over {planned_distance:.1f} m at that mean speed: {planned_distance / speed:.2f} s.")
    if elapsed < 60:
        checks.error("completed drive is shorter than 60 seconds")
    elif 75 <= elapsed <= 90:
        print("Preferred 75–90 s range met.")
    else:
        print("Minimum met. Outside the preferred 75–90 s range.")


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    commands = parser.add_subparsers(dest="command", required=True)
    project = commands.add_parser("project")
    project.add_argument("root", type=Path)
    project.add_argument("--required-scene", action="append", default=[])
    web = commands.add_parser("web")
    web.add_argument("root", type=Path)
    web.add_argument("site", type=Path)
    web.add_argument("--entry", default="play/index.html")
    route = commands.add_parser("route")
    route.add_argument("trace", type=Path)
    route.add_argument("--planned-distance-m", type=float)
    args = parser.parse_args()
    checks = Checks()
    try:
        if args.command == "project":
            check_project(args.root.resolve(strict=True), args.required_scene, checks)
        elif args.command == "web":
            check_web(args.root.resolve(strict=True), args.site.resolve(strict=True), args.entry, checks)
        else:
            check_route(args.trace, args.planned_distance_m, checks)
    except (OSError, ValueError, KeyError, TypeError) as exc:
        checks.error(str(exc))
    print(f"{checks.errors} error(s)")
    return int(bool(checks.errors))


if __name__ == "__main__":
    raise SystemExit(main())
